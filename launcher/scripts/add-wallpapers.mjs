// Adds your own wallpapers — your country, your city, your photos — without touching the bundled
// catalog. They go to src/img/wallpapers/local/ and src/js/wallpapers.local.js, both gitignored:
// they ship in your .wgt but never in the repository, so a fork starts with only the generic set.
//
//   node scripts/add-wallpapers.mjs <folder> [credits.json]
//
// Run it again with more photos to add to the same local set; a file with the same name replaces
// its earlier version. Local wallpapers are listed first in Settings → Background.
//
// credits.json: { "<key>": { "title": "...", "artist": "...", "license": "CC BY-SA 4.0", "position": "center 40%" } }
// where <key> is the file name without extension. The scrim is the island layout's: darker behind
// the centred clock and along the bottom where the dock sits, baked in like the original ones.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, statSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, extname, join, resolve } from 'node:path';

const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const sourceDir = resolve(process.argv[2] || '');
const credits = process.argv[3] ? JSON.parse(readFileSync(resolve(process.argv[3]), 'utf8')) : {};
const root = resolve(import.meta.dirname, '..');
const outDir = join(root, 'src/img/wallpapers/local');
const thumbDir = join(outDir, 'thumbs');
const catalogFile = join(root, 'src/js/wallpapers.local.js');

const SCRIM = [
    'radial-gradient(1200px 520px at 50% 18%, rgba(0,0,0,0.45), rgba(0,0,0,0) 72%)',
    'linear-gradient(to bottom, rgba(0,0,0,0.18) 0%, rgba(0,0,0,0.12) 40%, rgba(0,0,0,0.45) 75%, rgba(0,0,0,0.72) 100%)'
].join(',');

if (!statSync(sourceDir, { throwIfNoEntry: false })?.isDirectory()) {
    console.error('Usage: node scripts/add-wallpapers.mjs <folder> [credits.json]');
    process.exit(1);
}
mkdirSync(thumbDir, { recursive: true });

// Load the current local catalog by evaluating the generated file.
const sandbox = {};
if (existsSync(catalogFile)) new Function('window', readFileSync(catalogFile, 'utf8'))(sandbox);
const catalog = sandbox.WALLPAPERS_LOCAL || [];

const tmp = mkdtempSync(join(tmpdir(), 'wallpapers-'));
for (const file of readdirSync(sourceDir).sort()) {
    if (!/\.(jpe?g|png|webp)$/i.test(file)) continue;
    const key = basename(file, extname(file)).toLowerCase().replace(/[^a-z0-9]+/g, '-');
    const info = credits[key] || {};
    const html = join(tmp, key + '.html');
    const png = join(tmp, key + '.png');
    const src = 'file://' + join(sourceDir, file).split('/').map(encodeURIComponent).join('/');
    writeFileSync(html, `<!DOCTYPE html><body style="margin:0;width:1920px;height:1080px;background:${SCRIM},` +
        `url('${src}') ${info.position || 'center'} / cover no-repeat #000"></body>`);
    execFileSync(CHROME, ['--headless=new', '--disable-gpu', '--hide-scrollbars', '--window-size=1920,1080',
        '--allow-file-access-from-files', '--virtual-time-budget=5000', `--user-data-dir=${join(tmp, 'profile')}`,
        `--screenshot=${png}`, 'file://' + html], { stdio: 'ignore' });
    const out = join(outDir, key + '.jpg');
    execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '82', png, '--out', out], { stdio: 'ignore' });
    execFileSync('sips', ['-Z', '320', '-s', 'formatOptions', '78', out, '--out', join(thumbDir, key + '.jpg')], { stdio: 'ignore' });
    const entry = {
        key,
        title: info.title || key,
        file: 'img/wallpapers/local/' + key + '.jpg',
        thumb: 'img/wallpapers/local/thumbs/' + key + '.jpg',
        credit: [info.artist, info.license].filter(Boolean).join(' · ')
    };
    const at = catalog.findIndex((w) => w.key === key);
    if (at >= 0) catalog[at] = entry; else catalog.push(entry);
    console.log(`${key}.jpg  ${(statSync(out).size / 1024).toFixed(0)} KB  ${entry.credit}`);
}
rmSync(tmp, { recursive: true, force: true });

writeFileSync(catalogFile,
    '/* Generated by scripts/add-wallpapers.mjs — local wallpapers, gitignored. Each credit names\n' +
    ' * the photographer and licence. Listed before the bundled set. */\n' +
    'window.WALLPAPERS_LOCAL = ' + JSON.stringify(catalog, null, 4) + ';\n' +
    'window.WALLPAPERS = window.WALLPAPERS_LOCAL.concat(window.WALLPAPERS || []);\n');
console.log(`Local catalog now has ${catalog.length} wallpapers`);
